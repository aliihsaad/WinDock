import { createChecker } from "./lib/assert.mjs";
import { createClipboardHistory, normalizeHistory, parseElephantHistory } from "../src/platform/clipboard.js";
import { validateInput } from "../src/input.js";
import { createApp } from "../server.js";
import { WebSocket } from "ws";
import { once } from "node:events";

const t = createChecker("clipboard");
const text = "line one\nمرحبا 🙂\tend";
t.deepEqual(normalizeHistory({items:[{text},{text}]}).items, [{text}], "history is deduplicated without changing Unicode or whitespace");
t.equal(normalizeHistory({items:[{text:"x".repeat(32769)},{text:"bad\0text"},{text:"\ud800"}]}).items.length, 0, "oversize, controls and malformed Unicode rejected");
t.equal(normalizeHistory({items:Array.from({length:30},(_,i)=>({text:String(i)}))}).items.length, 20, "recent entries are bounded");
t.equal(normalizeHistory({items:Array.from({length:20},(_,i)=>({text:String(i).padEnd(32768,"x")}))}).items.length, 4, "aggregate text budget is bounded");
const row = item => JSON.stringify({qid:1,item});
const elephant = [row({provider:"clipboard",preview_type:"text",text:"truncated",preview:text}),row({provider:"clipboard",preview_type:"file",preview:"/private/image.png"}),row({provider:"clipboard",preview_type:"command",preview:"do not execute"}),row({provider:"files",preview_type:"text",preview:"not clipboard"}),"{}"].join("\n");
t.deepEqual(parseElephantHistory(elephant).items,[{text}],"Elephant NDJSON uses full text previews and ignores commands/files/other providers");
t.deepEqual(parseElephantHistory("{}").items,[],"empty Elephant response is handled");
t.throws(()=>parseElephantHistory("not json"),"invalid CLI response rejected");
let command;
const provider = createClipboardHistory({platform:"linux",execFile:(file,args,options,done)=>{command={file,args,options};done(null,elephant);}});
t.deepEqual((await provider.history()).items,[{text}],"Linux history parses the actual CLI schema");
t.deepEqual(command.args,["query","--json","clipboard;;20"],"only the fixed clipboard query is executed");
t.equal(command.options.shell,false,"no shell evaluates clipboard data");
t.ok(command.options.timeout > 0 && command.options.maxBuffer <= 2097152,"process time and output are bounded");
const privateError=createClipboardHistory({platform:"windows",helperPath:"fake",execFile:(_f,_a,_o,done)=>done(Object.assign(new Error("secret clipboard text"),{stdout:"secret"}))});
const nativeError = await privateError.history().then(()=>null,error=>error);
t.ok(nativeError?.status === 503 && !nativeError.message.includes("secret"),"native errors cannot expose clipboard stdout or content");
let finish;
const slow=createClipboardHistory({platform:"windows",helperPath:"fake",execFile:(_f,_a,_o,done)=>{finish=done;}});
const first=slow.history(); await t.rejects(()=>slow.history(),"parallel history loads are bounded"); finish(null,'{"status":"disabled","items":[]}');
t.equal((await first).status,"disabled","disabled Windows history is explicit");
for(const value of [text,"x".repeat(32768)]) t.deepEqual(validateInput({type:"paste",target:"2",text:value}),{type:"paste",target:"2",text:value},"bounded paste accepted");
for(const value of ["","x".repeat(32769),"bad\0", "\ud800"]) t.equal(validateInput({type:"paste",target:"2",text:value}),null,"invalid paste rejected");
t.equal(validateInput({type:"paste",target:"0",text}),null,"paste requires a valid target");
t.equal(validateInput({type:"paste",target:"2",text,extra:true}),null,"extra paste fields rejected");

let reads=0, inputEvent, complete;
const app=await createApp({provider:{id:"clipboard-test",displayName:"Fixture",listRunningApps:async()=>[],clipboard:{history:async()=>{reads++;return {status:"ready",items:[{text}]};}},input:{open(_fail,emit){complete=emit;emit({type:"focus",target:"2",editable:true,password:false});return {ready:Promise.resolve(),close(){},send(value){if(value.type==="paste")inputEvent=value;}};},dispose(){}}},pin:"864213",trustLoopback:false,configStore:{load:async()=>({tiles:[]})}});
await new Promise(resolve=>app.server.listen(0,"127.0.0.1",resolve));
const base=`http://127.0.0.1:${app.server.address().port}`;
let ws;
try {
  t.equal((await fetch(base+"/api/clipboard/history")).status,401,"unpaired history is rejected");
  t.equal(reads,0,"unpaired requests never read the PC clipboard");
  const auth=await fetch(base+"/api/auth",{method:"POST",headers:{origin:base,"content-type":"application/json"},body:JSON.stringify({pin:"864213"})});
  const cookie=auth.headers.get("set-cookie").split(";")[0];
  t.equal((await fetch(base+"/api/clipboard/history",{headers:{cookie,origin:"https://example.invalid"}})).status,403,"cross-origin history is rejected");
  t.equal(reads,0,"cross-origin requests never read history");
  const history=await fetch(base+"/api/clipboard/history",{headers:{cookie,origin:base}});
  t.equal(history.headers.get("cache-control"),"no-store","clipboard is never HTTP-cached");
  t.deepEqual((await history.json()).items,[{text}],"paired history preserves exact text");
  t.equal(reads,1,"one explicit fetch performs one history read");
  ws=new WebSocket(base.replace("http:","ws:")+"/input",{headers:{cookie,origin:base}});
  const messages=[]; ws.on("message",data=>messages.push(JSON.parse(data.toString())));
  await once(ws,"open"); await new Promise(resolve=>setTimeout(resolve,20));
  const large="🙂".repeat(12000);
  ws.send(JSON.stringify({type:"paste",target:"2",text:large})); await new Promise(resolve=>setTimeout(resolve,20));
  t.equal(inputEvent.text,large,"large clipboard paste reaches the owned input worker intact");
  ws.send(JSON.stringify({type:"paste",target:"2",text:"second"})); await new Promise(resolve=>setTimeout(resolve,20));
  t.equal(inputEvent.text,large,"second paste is blocked until completion");
  complete({type:"paste-result"}); await new Promise(resolve=>setTimeout(resolve,20));
  t.ok(messages.some(message=>message.type==="paste-result"),"native paste completion reaches the phone");
} finally { ws?.terminate(); await app.inputHub.close(); await app.hub.close(); app.server.closeAllConnections(); await new Promise(resolve=>app.server.close(resolve)); }
t.done("clipboard verification passed");
