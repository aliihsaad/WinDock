// Run with playwright-cli run-code after starting scripts/website-server.mjs.
async (page) => {
  const browser = page.context().browser(), results = [], contexts = [];
  const check = (ok, name) => { if (!ok) throw new Error(name); results.push(name); };
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', reducedMotion: 'reduce', serviceWorkers: 'block' });
    contexts.push(context);
    await context.addInitScript(() => {
      window.realClipboardCalls = 0;
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: {
        read() { window.realClipboardCalls++; throw new Error('Real clipboard must not be read'); },
        readText() { window.realClipboardCalls++; throw new Error('Real clipboard must not be read'); },
        write() { window.realClipboardCalls++; throw new Error('Real clipboard must not be written'); },
        writeText() { window.realClipboardCalls++; throw new Error('Real clipboard must not be written'); },
      } });
    });
    const tab = await context.newPage(), errors = [], clipboardRequests = [], deviceRequests = [];
    tab.on('pageerror', error => errors.push(error.message));
    tab.on('request', request => { if (request.url().includes('/api/clipboard')) clipboardRequests.push(request.url()); });
    tab.on('request', request => { if (/192\.0\.2\.|\/api\/(state|input|auth|tiles|apps|capture)/.test(request.url())) deviceRequests.push(request.url()); });
    await tab.goto('http://127.0.0.1:4173');
    await tab.getByRole('button', { name: 'No thanks', exact: true }).click();
    const demo = tab.frameLocator('#demo-frame');
    await demo.locator('#app:not([hidden])').waitFor();
    check(await tab.locator('#desktop-navigation').isHidden() && (await tab.locator('.nav-shell').boundingBox()).width === 52, 'Desktop navigation starts as the compact WinDock icon with reduced motion');
    await tab.locator('#nav-toggle').hover();
    await tab.locator('.desktop-nav').waitFor({ state: 'visible' });
    check((await tab.locator('.nav-shell').boundingBox()).width > 700, 'Hover expands the desktop navigation');
    await tab.mouse.move(1000, 200);
    await tab.locator('#desktop-navigation').waitFor({ state: 'hidden' });
    check(await tab.locator('#desktop-navigation').evaluate(el => el.inert), 'Leaving collapses navigation and removes hidden links from the tab order');
    await tab.keyboard.press('Tab');
    await tab.locator('#nav-toggle').focus();
    await tab.locator('.desktop-nav').waitFor({ state: 'visible' });
    await tab.keyboard.press('Tab');
    check(await tab.locator('.nav-content .brand').evaluate(el => el === document.activeElement), 'Keyboard focus expands the bar and reaches its links');
    await tab.keyboard.press('Escape');
    check(await tab.locator('#nav-toggle').evaluate(el => el === document.activeElement) && await tab.locator('#desktop-navigation').isHidden(), 'Escape collapses desktop navigation and restores focus to its icon');
    check(await tab.locator('.release-entry').count() === 0, 'Detailed release history is off the homepage');
    await tab.screenshot({ path: 'output/playwright/redesign-desktop.png' });
    check(await tab.locator('.release-highlights article').count() === 4, 'Dedicated release section has four feature highlights');
    check(!(await tab.locator('#next-release').innerText()).includes('IN TESTING'), 'Release section introduces 0.2.5 without a testing label');
    await tab.locator('#download-windows:not([aria-disabled="true"])').waitFor();
    for (const id of ['download-windows', 'download-android', 'download-linux-arch', 'download-linux-deb']) {
      check((await tab.locator('#' + id).getAttribute('href')).includes('/v0.2.5-preview.3/'), id + ' points to the verified 0.2.5 release');
    }
    // The real dock button must work too, not just the marketing shortcut.
    await tab.locator('#preview-drawer').click();
    await demo.locator('#drawer-switch-pc').click();
    await tab.locator('#pc-demo-picker[open]').waitFor();
    check(await tab.locator('.pc-demo-row').count() === 3, 'Native picker demo shows available and saved PCs');
    await tab.locator('[data-select-pc="omarchy"]').click();
    await tab.locator('#pc-demo-picker').waitFor({ state: 'hidden' });
    check(await demo.locator('#drawer-host').textContent() === 'Omarchy', 'Switching to Linux updates the actual demo dock');
    check((await tab.locator('#demo-current-pc').innerText()).includes('Linux'), 'Selected platform is visible beside the dock');
    await tab.locator('#preview-pc-picker').click();
    await tab.getByRole('button', { name: 'Forget Studio PC', exact: true }).click();
    await tab.locator('#pc-demo-cancel').click();
    check(await tab.getByRole('button', { name: 'Forget Studio PC', exact: true }).count() === 1, 'Cancelling Forget retains the saved PC');
    await tab.getByRole('button', { name: 'Forget Studio PC', exact: true }).click();
    await tab.locator('#pc-demo-forget').click();
    await tab.getByRole('button', { name: 'Forget Studio PC', exact: true }).waitFor({ state: 'detached' });
    check(await tab.locator('[data-select-pc="studio"]').count() === 1, 'A forgotten running PC remains available for explicit selection');
    await tab.locator('#pc-demo-refresh').click();
    await tab.locator('#pc-demo-status').filter({ hasText: 'Sample PCs refreshed' }).waitFor();
    check(await tab.getByRole('button', { name: 'Forget Studio PC', exact: true }).count() === 0, 'Refresh does not silently remember a forgotten PC');
    await tab.locator('[data-select-pc="travel"]').click();
    check((await tab.locator('#pc-demo-status').innerText()).includes('offline'), 'Offline saved PC explains why it cannot connect');
    check(await demo.locator('#drawer-host').textContent() === 'Omarchy', 'Offline selection preserves the current dock');
    await tab.getByRole('button', { name: 'Forget Travel laptop', exact: true }).click();
    await tab.locator('#pc-demo-forget').click();
    await tab.locator('[data-select-pc="travel"]').waitFor({ state: 'detached' });
    await tab.locator('#pc-demo-close').click();
    await tab.locator('#preview-pc-picker').click();
    check(await tab.locator('[data-select-pc="travel"]').count() === 0, 'Forgetting a saved offline PC survives reopening the sample picker');
    await tab.locator('[data-select-pc="studio"]').click();
    await tab.locator('#pc-demo-picker').waitFor({ state: 'hidden' });
    check(await demo.locator('#drawer-host').textContent() === 'Studio PC', 'Explicitly choosing the Windows PC reconnects its sample dock');
    check(deviceRequests.length === 0, 'PC discovery and switching make no device or host API requests');
    await tab.locator('#preview-capture').click();
    await demo.locator('#capture[open]').waitFor();
    await demo.locator('#capture-screenshot').click();
    await demo.locator('#capture-file').filter({ hasText: 'No file created' }).waitFor();
    check(true, 'Capture shortcut still produces explicit simulated screenshot feedback');
    await demo.locator('#capture-record').click();
    // Starting a recording intentionally returns to the dock in the real app.
    await tab.locator('#preview-pc-picker').click();
    await tab.locator('#pc-demo-picker[open]').waitFor();
    await tab.locator('[data-select-pc="omarchy"]').click();
    await tab.locator('#pc-demo-picker').waitFor({ state: 'hidden' });
    await tab.locator('#preview-capture').click();
    await demo.locator('#capture[open]').waitFor();
    check(await demo.locator('#capture-record-label').textContent() === 'Start recording', 'Capture state belongs to the selected sample PC');
    await tab.locator('#preview-pc-picker').click();
    await tab.locator('#pc-demo-picker[open]').waitFor();
    await tab.locator('[data-select-pc="studio"]').click();
    await tab.locator('#pc-demo-picker').waitFor({ state: 'hidden' });
    await tab.locator('#preview-capture').click();
    await demo.locator('#capture-record-label').filter({ hasText: 'Stop recording' }).waitFor();
    check(true, 'Returning to the first PC preserves its simulated recording');
    await demo.locator('#capture-record').click();
    await demo.locator('#capture-file').filter({ hasText: 'Demo recording.mp4' }).waitFor();
    check(true, 'Recording preview starts and stops without creating media');
    await tab.locator('#preview-signature').click();
    await demo.locator('#signature-canvas').waitFor({ state: 'visible' });
    check(true, 'Signature shortcut opens the shipping signature UI');
    await tab.locator('[data-preview-clipboard]').click();
    await demo.locator('.pc-clipboard__item').first().waitFor();
    check(await demo.locator('.pc-clipboard__item').count() === 3, 'Release CTA opens three fictional clipboard samples');
    check(await tab.locator('#demo-typing').isHidden(), 'Browsing samples does not paste');
    await demo.locator('.pc-clipboard__item').nth(1).click();
    check((await demo.locator('#pc-clipboard-text').inputValue()).includes('Coffee\nBread'), 'Selecting a sample preserves multiline text');
    check(await tab.locator('#demo-typing').isHidden(), 'Selecting a sample does not paste');
    await demo.locator('#pc-clipboard-text').fill('Edited demo text\nمرحبا 🙂');
    await demo.getByRole('button', { name: 'Try paste', exact: true }).click();
    await tab.waitForFunction(() => document.getElementById('demo-typed-text').textContent === 'Edited demo text\nمرحبا 🙂');
    check((await demo.locator('#pc-clipboard-status').innerText()).includes('Nothing was pasted on your PC'), 'Paste confirms the simulation');
    await demo.locator('#pc-clipboard-close').click();
    check(await demo.locator('.pc-clipboard__item').count() === 0 && await demo.locator('#pc-clipboard-text').inputValue() === '', 'Closing the demo panel clears the samples and editor');
    await tab.locator('#demo-clear-text').click();
    await tab.waitForFunction(() => document.getElementById('demo-typed-text').textContent === 'Your demo text will appear here.');
    check(await tab.locator('#demo-typed-text').innerText() === 'Your demo text will appear here.', 'Demo output can be cleared');
    const frame = tab.frames().find(frame => frame.url().includes('/demo/index.html'));
    check(await frame.evaluate(() => window.realClipboardCalls) === 0 && clipboardRequests.length === 0, 'Demo never calls the real clipboard or a clipboard endpoint');
    await demo.locator('.touchpad-navigation [data-close="input-pad"]').click();
    await tab.locator('#preview-drawer').click();
    await demo.locator('#drawer-updates').click();
    await demo.locator('#updates-check').click();
    await demo.locator('#updates-status').filter({ hasText: 'Demo check complete' }).waitFor();
    check(await demo.locator('#updates-download').isHidden(), 'Simulated update check does not invent a release download');
    await demo.locator('[data-close="updates"]').click();
    await tab.evaluate(() => document.activeElement?.blur());
    for (const width of [1440, 768, 390, 320]) {
      await tab.setViewportSize({ width, height: 1000 });
      await tab.locator('#next-release').scrollIntoViewIfNeeded();
      check(await tab.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No horizontal overflow at ' + width + 'px');
      const heading = await tab.locator('#release-spotlight-title').boundingBox();
      check(heading.width > 0 && heading.x >= 0 && heading.x + heading.width <= width, 'Release heading fits at ' + width + 'px');
      if (width === 1440 || width === 390) await tab.locator('#next-release').screenshot({ path: 'output/playwright/release-spotlight-' + width + '.png' });
    }
    await tab.locator('#preview-pc-picker').click();
    await tab.locator('#pc-demo-picker[open]').waitFor();
    const pickerBounds = await tab.locator('#pc-demo-picker').boundingBox();
    check(pickerBounds.x >= 0 && pickerBounds.width <= 320 && pickerBounds.height <= 1000, 'PC picker fits a 320px phone without inheriting dock scaling');
    check(await tab.locator('.pc-demo-select strong').first().evaluate(el => parseFloat(getComputedStyle(el).fontSize)) >= 14, 'Sample PC names remain readable on phones');
    await tab.screenshot({ path: 'output/playwright/redesign-picker-mobile.png' });
    await tab.keyboard.press('Escape');
    check(await tab.locator('#pc-demo-picker').isHidden() && await tab.locator('#preview-pc-picker').evaluate(el => el === document.activeElement), 'Escape closes the picker and returns keyboard focus');
    await tab.locator('#nav-toggle').click();
    await tab.locator('#mobile-menu[open]').waitFor();
    await tab.locator('#mobile-theme-toggle').click();
    check(await tab.locator('html').getAttribute('data-theme') === 'dark', 'Mobile navigation retains its dark mode control');
    await tab.locator('#mobile-menu a[href="./setup.html"]').click();
    await tab.waitForURL('**/setup.html');
    check(await tab.locator('#linux-help').count() === 1 && await tab.locator('.faq-list details').count() >= 10, 'Dedicated help page retains Linux setup and detailed FAQs');
    check(await tab.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Long Linux commands scroll within the guide on narrow phones');
    check(await tab.locator('#analytics-notice').isHidden(), 'Analytics choice persists across pages');
    check(await tab.locator('html').getAttribute('data-theme') === 'dark', 'Theme preference persists on the help page');
    await tab.goto('http://127.0.0.1:4173/releases.html');
    check(await tab.locator('.release-entry').count() >= 6, 'Release page retains all historical releases');
    check(await tab.locator('article.release-entry').count() === 1 && await tab.locator('#candidate-release ul').isVisible() && await tab.locator('details.release-entry[open]').count() === 0, 'Only the latest release is expanded by default');
    const previousRelease = tab.locator('details.release-entry').first();
    await previousRelease.locator('summary').click();
    check(await previousRelease.locator('ul').isVisible() && (await previousRelease.locator('.release-version').textContent()) === '0.2.4-preview.1', 'The previous release opens to show its complete notes');
    await previousRelease.locator('summary').focus();
    await tab.keyboard.press('Space');
    check(await previousRelease.locator('ul').isHidden(), 'The previous release can also be collapsed using the keyboard');
    check(await tab.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Release history fits narrow phones');
    await tab.goto('http://127.0.0.1:4173/#history');
    await tab.waitForURL('**/releases.html#history');
    check(true, 'Old history bookmarks still reach the release notes');
    await tab.goto('http://127.0.0.1:4173');
    await tab.locator('#preview-pc-picker').click();
    await tab.locator('#pc-demo-picker[open]').waitFor();
    check(await tab.locator('[data-select-pc="travel"]').count() === 1 && await tab.locator('[data-pc="studio"][data-current="true"]').count() === 1, 'Reload resets fictional PCs instead of persisting device data');
    await tab.locator('#pc-demo-close').click();
    await tab.setViewportSize({ width: 1440, height: 1000 });
    await tab.locator('#demo-expand').click();
    await tab.waitForFunction(() => document.fullscreenElement?.id === 'experience');
    await tab.locator('#preview-pc-picker').click();
    await tab.locator('#pc-demo-picker[open]').waitFor();
    check(await tab.locator('#pc-demo-picker').isVisible(), 'The PC picker remains usable in the expanded demo');
    await tab.locator('[data-select-pc="omarchy"]').click();
    await tab.locator('#pc-demo-picker').waitFor({ state: 'hidden' });
    await tab.locator('#demo-expand').click();
    await tab.waitForFunction(() => !document.fullscreenElement);
    check(await demo.locator('#drawer-host').textContent() === 'Omarchy', 'Expanding and collapsing preserves the selected demo PC');
    await tab.evaluate(() => scrollTo(0, 0));
    await tab.screenshot({ path: 'output/playwright/redesign-dark.png' });
    await tab.setViewportSize({ width: 390, height: 844 });
    await tab.locator('#nav-toggle').click();
    await tab.locator('#mobile-theme-toggle').click();
    await tab.keyboard.press('Escape');
    await tab.evaluate(() => scrollTo(0, 0));
    await tab.screenshot({ path: 'output/playwright/redesign-mobile.png' });
    await tab.locator('#nav-toggle').click();
    await tab.locator('#mobile-theme-toggle').click();
    await tab.keyboard.press('Escape');
    await tab.locator('#next-release').screenshot({ path: 'output/playwright/release-spotlight-dark.png' });
    check(deviceRequests.length === 0, 'All demo shortcuts stay isolated from device APIs');
    check(errors.length === 0, 'No uncaught website or demo errors');
    return { passed: results.length, results };
  } finally { for (const context of contexts) await context.close(); }
}
