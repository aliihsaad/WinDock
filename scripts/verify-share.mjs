import { createChecker } from "./lib/assert.mjs";
import { createClipboardText, validShareText } from "../src/clipboard-text.js";
import { normalizeTile } from "../src/config.js";
import { addPhoneControlTile, tileKey, toWireTiles } from "../public/tiles.js";
import { renderTile } from "../public/dock.js";
const t = createChecker("share");
t.equal(validShareText("hello"), true, "plain text is shareable");
t.deepEqual([validShareText(""), validShareText("a\x00b"), validShareText("x".repeat(32769))], [false, false, false], "empty, control and oversized text are refused");
const calls = [];
const fake = (out) => (file, args, opts, cb) => { calls.push({ file, args }); const stdin = { on() {}, end(text) { calls.at(-1).input = text; } }; queueMicrotask(() => cb(null, out)); return { stdin }; };
const win = createClipboardText({ platform: "win32", execFile: fake("copied text\r\n") });
t.equal((await win.get()).text, "copied text", "Windows read trims the trailing newline");
await win.set("from phone");
t.deepEqual([calls.at(-1).file, calls.at(-1).input], ["powershell.exe", "from phone"], "Windows write sends text on stdin, not in the command line");
const bad = createClipboardText({ platform: "linux", execFile: (f, a, o, cb) => { queueMicrotask(() => cb(new Error("secret stdout"))); return { stdin: { on() {}, end() {} } }; } });
const failure = await bad.get().catch((e) => e);
t.deepEqual([failure.status, failure.message.includes("secret")], [503, false], "process errors are not forwarded");
t.equal((await createClipboardText({ platform: "linux", execFile: fake("x") }).set("").catch((e) => e.status)), 400, "empty write is rejected");
t.deepEqual(normalizeTile({ kind: "tool", id: "tool:phone-control", label: "PC control on phone Tara" }), { kind: "tool", id: "tool:phone-control", label: "PC control on phone Tara" }, "host accepts the tool tile");
t.equal(normalizeTile({ kind: "tool", id: "tool:other" }), null, "unknown tools are refused");
const once = addPhoneControlTile([]);
t.deepEqual([once.length, addPhoneControlTile(once).length, tileKey(once[0])], [1, 1, "tool:phone-control"], "tile is added once");
t.equal(toWireTiles(once)[0].kind, "tool", "tile survives the wire round trip");
const html = renderTile(once[0]);
t.deepEqual([html.includes("PC control on phone Tara"), html.includes('data-action="tool"') || html.includes("tool")], [true, true], "dock renders the tile");
t.done("share verification passed");
